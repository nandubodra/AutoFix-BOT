CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE websites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    normalized_url VARCHAR(2048) NOT NULL,
    verified BOOLEAN NOT NULL,
    verification_token VARCHAR(128) NOT NULL,
    monitoring_enabled BOOLEAN NOT NULL,
    interval_seconds INT NOT NULL,
    timeout_ms INT NOT NULL,
    expected_statuses VARCHAR(128) NOT NULL,
    failure_threshold INT NOT NULL,
    recovery_threshold INT NOT NULL,
    status VARCHAR(32) NOT NULL,
    consecutive_failures INT NOT NULL,
    consecutive_successes INT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_check_at TIMESTAMP WITH TIME ZONE,
    next_check_at TIMESTAMP WITH TIME ZONE,
    claim_until TIMESTAMP WITH TIME ZONE,
    version BIGINT NOT NULL
);

CREATE INDEX idx_websites_due ON websites (monitoring_enabled, verified, next_check_at, claim_until);
CREATE INDEX idx_websites_owner ON websites (owner_id);

CREATE TABLE check_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    website_id BIGINT NOT NULL REFERENCES websites(id) ON DELETE CASCADE,
    success BOOLEAN NOT NULL,
    http_status INT,
    duration_ms BIGINT NOT NULL,
    failure_category VARCHAR(64) NOT NULL,
    failure_summary VARCHAR(512) NOT NULL,
    retry_number INT NOT NULL,
    checked_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_check_results_site_time ON check_results (website_id, checked_at DESC);

CREATE TABLE incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    website_id BIGINT NOT NULL REFERENCES websites(id) ON DELETE CASCADE,
    status VARCHAR(32) NOT NULL,
    fingerprint VARCHAR(128) NOT NULL,
    severity VARCHAR(16) NOT NULL,
    description VARCHAR(512) NOT NULL,
    first_detected_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen_at TIMESTAMP WITH TIME ZONE NOT NULL,
    acknowledged_at TIMESTAMP WITH TIME ZONE,
    resolved_at TIMESTAMP WITH TIME ZONE,
    occurrences BIGINT NOT NULL,
    first_check_result_id BIGINT REFERENCES check_results(id),
    last_check_result_id BIGINT REFERENCES check_results(id)
);

CREATE INDEX idx_incident_active ON incidents (website_id, status, fingerprint, last_seen_at DESC);

CREATE TABLE alert_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT NOT NULL REFERENCES incidents(id) ON DELETE CASCADE,
    website_id BIGINT NOT NULL REFERENCES websites(id) ON DELETE CASCADE,
    alert_type VARCHAR(32) NOT NULL,
    status VARCHAR(32) NOT NULL,
    recipient_email VARCHAR(320) NOT NULL,
    dedup_key VARCHAR(128) NOT NULL,
    attempt_count INT NOT NULL,
    last_attempt_at TIMESTAMP WITH TIME ZONE,
    next_attempt_at TIMESTAMP WITH TIME ZONE,
    error_summary VARCHAR(512),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_alert_dedup UNIQUE (dedup_key)
);

CREATE INDEX idx_alert_retry ON alert_deliveries (status, next_attempt_at);
